def build_8x16_font_table() -> bytes:
    """Return 95 * 16 = 1,520 bytes (plus 16B pad -> 1,536B) for ASCII 0x20..0x7E."""
    out = bytearray()
    for code in range(0x20, 0x7F):
        ch = chr(code)
        rows = _GLYPHS_8X16[ch]
        if len(rows) != 16:
            raise ValueError(f"Glyph {ch!r} has {len(rows)} rows")
        for r in rows:
            if len(r) != 8:
                raise ValueError(f"Glyph {ch!r} row width {len(r)} != 8")
            val = 0
            for idx, px in enumerate(r):
                if px != ".":
                    val |= 1 << (7 - idx)
            out.append(val)
    out.extend(b"\x00" * 16)
    return bytes(out)


def glyph_trimmed_bitmap(ch: str) -> List[List[int]]:
    """Return tight-width binary pixel matrix (10 rows tall: rows 1..11) for crisp UI text."""
    rows = _GLYPHS_8X16.get(ch, _GLYPHS_8X16[" "])
    if ch == " ":
        return [[0] * 3 for _ in range(11)]
    # Rows 1..11 capture ascenders + descenders cleanly (11 px tall)
    mat = [[1 if c != "." else 0 for c in r] for r in rows[1:12]]
    min_x = 8
    max_x = -1
    for row in mat:
        for x, v in enumerate(row):
            if v:
                min_x = min(min_x, x)
                max_x = max(max_x, x)
    if max_x < min_x:
        return [[0] * 3 for _ in range(11)]
    return [row[min_x : max_x + 1] for row in mat]


def measure_proportional_11px(text: str, spacing: int = 1) -> int:
    """Measure width in pixels using trimmed 8x16 glyphs + 1px spacing."""
    w = 0
    for i, ch in enumerate(text):
        bm = glyph_trimmed_bitmap(ch)
        w += len(bm[0])
        if i + 1 < len(text):
            w += spacing
    return w


def render_proportional_11px(
    canvas: List[List[int]],
    text: str,
    x0: int,
    y0: int,
    fg_idx: int,
    outline_idx: int | None = None,
    spacing: int = 1,
) -> None:
    """Draw trimmed 11px-tall proportional pixel text onto indexed canvas (in-place)."""
    h = len(canvas)
    w = len(canvas[0])
    pts = []
    cx = x0
    for ch in text:
        bm = glyph_trimmed_bitmap(ch)
        gw = len(bm[0])
        for dy, row in enumerate(bm):
            for dx, v in enumerate(row):
                if v:
                    pts.append((cx + dx, y0 + dy))
        cx += gw + spacing

    if outline_idx is not None:
        for px, py in pts:
            for oy in (-1, 0, 1):
                for ox in (-1, 0, 1):
                    nx, ny = px + ox, py + oy
                    if 0 <= nx < w and 0 <= ny < h:
                        canvas[ny][nx] = outline_idx
    for px, py in pts:
        if 0 <= px < w and 0 <= py < h:
            canvas[py][px] = fg_idx
